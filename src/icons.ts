export function registerIconSets(): void {
  window.customIconsets = window.customIconsets ?? {};

  for (const [setName, icons] of Object.entries(ICON_SETS)) {
    window.customIconsets[setName] = async (iconName) => {
      const icon = icons[iconName];
      if (!icon) {
        throw new Error(
          `[hass-custom] icon "${setName}:${iconName}" is not defined`
        );
      }
      return { path: icon.path, viewBox: icon.viewBox ?? "0 0 24 24" };
    };
  }
}

export function iconSetNames(): string[] {
  return Object.keys(ICON_SETS);
}
